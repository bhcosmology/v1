/* ============================================================
   i18n runtime
   ============================================================ */
(function () {
  var SUPPORTED = ['ca', 'es', 'en'];

  // ── page-transition veil: a brief, dim "jump to hyperspace" — dim stars
  //    streak left→right for a moment, then dissolve to the page.
  //    A solid ::before guarantees the very first paint is covered (no flash);
  //    a canvas on top of it runs the warp.
  var veilStyle = document.createElement('style');
  veilStyle.textContent = 'html::before{content:"";position:fixed;inset:0;z-index:99998;'
    + 'background:#020204;pointer-events:none;opacity:1;transition:opacity .45s ease}'
    + 'html.bhc-ready::before{opacity:0}';
  (document.head || document.documentElement).appendChild(veilStyle);

  // guard: if this file is ever loaded twice, drop the stale canvas so only one
  // veil is ever on screen (a second visible loop reads as a doubled animation)
  var stale = document.getElementById('bhc-warp');
  if (stale && stale.parentNode) stale.parentNode.removeChild(stale);
  var warp = document.createElement('canvas');
  warp.id = 'bhc-warp';
  warp.style.cssText = 'position:fixed;top:0;left:0;width:100vw;height:100vh;z-index:99999;'
    + 'pointer-events:none;background:#020204;opacity:1;transition:opacity .45s ease';
  (document.body || document.documentElement).appendChild(warp);

  var wctx = warp.getContext ? warp.getContext('2d') : null;
  var DPR = Math.min(window.devicePixelRatio || 1, 2);
  var W = 0, H = 0, wstars = [], wraf = 0, wrunning = false, wstopTimer = 0, wt0 = 0, wphase0 = 0;
  var FOCAL = 0, ZNEAR = 0.07, ZFAR = 2.9, DUR = 1500;
  function wsize() {
    W = warp.width = Math.max(1, Math.round(window.innerWidth * DPR));
    H = warp.height = Math.max(1, Math.round(window.innerHeight * DPR));
    FOCAL = Math.max(W, H) * 0.9;
  }
  // Flight direction as a 3D unit vector, re-rolled for every jump: random yaw
  // and pitch put the vanishing point somewhere new, and the sign of the z
  // component decides whether we fly forward into the field or back out of it.
  var DIR = { x: 0, y: 0, z: 1 }, BACK = false;
  function wdir() {
    BACK = Math.random() < 0.5;                      // half the jumps run in reverse
    var ax = (Math.random() * 2 - 1) * 0.55;         // yaw
    var ay = (Math.random() * 2 - 1) * 0.55;         // pitch
    var az = 0.72 + Math.random() * 0.5;
    var m = Math.sqrt(ax * ax + ay * ay + az * az) || 1;
    var sgn = BACK ? -1 : 1;
    DIR.x = (ax / m) * sgn; DIR.y = (ay / m) * sgn; DIR.z = (az / m) * sgn;
  }

  // ── one jump across two pages ──────────────────────────────────────────────
  // Leaving a page runs the accelerating half of the jump; the page we land on
  // resumes the SAME heading and finishes the decelerating half. Without this
  // handoff you get two unrelated jumps back to back (out, then in).
  var HANDOFF = 'bhc_jump';
  function saveJump() {
    try {
      sessionStorage.setItem(HANDOFF, JSON.stringify({
        x: DIR.x, y: DIR.y, z: DIR.z, b: BACK, ts: Date.now()
      }));
    } catch (e) {}
  }
  function takeJump() {                              // returns true if we resumed one
    var raw = null;
    try { raw = sessionStorage.getItem(HANDOFF); sessionStorage.removeItem(HANDOFF); } catch (e) {}
    if (!raw) return false;
    try {
      var j = JSON.parse(raw);
      if (!j || Date.now() - j.ts > 4000) return false;   // stale → treat as a fresh arrival
      DIR.x = j.x; DIR.y = j.y; DIR.z = j.z; BACK = !!j.b;
      return true;
    } catch (e) { return false; }
  }
  // Spawn by picking a point on screen and back-projecting it to depth z, so a
  // star is always framed correctly whichever way we're travelling.
  function wmake(z) {
    return {
      x: (Math.random() * 2 - 1) * 0.75 * z,
      y: (Math.random() * 2 - 1) * 0.75 * z,
      z: z,
      v: 0.55 + Math.random() * 0.75,                // per-star speed jitter
      px: null, py: null
    };
  }
  function wrecycle() {                              // re-enter from whichever end we came from
    return wmake(BACK ? (0.16 + Math.random() * 0.3) : (ZFAR - 0.5 + Math.random() * 0.5));
  }
  function wseed() {
    wstars = [];
    for (var i = 0; i < 170; i++) wstars.push(wmake(0.25 + Math.random() * (ZFAR - 0.4)));
  }
  // slow → fast → slow: a sine bell over the nominal jump length, with a floor
  // so it never fully stalls while the veil is still up. wphase0 says where in
  // that curve this run begins — 0 when launching, 0.5 (the peak) when landing.
  function wspeed(now) {
    var t = Math.min(1, wphase0 + (now - wt0) / DUR);
    return 0.14 + 0.86 * Math.sin(Math.PI * t);
  }
  function wframe(now) {
    if (!wctx) return;
    now = now || performance.now();
    var ease = wspeed(now);
    wctx.fillStyle = 'rgba(2,2,4,0.30)';             // translucent clear → motion-blur streaks
    wctx.fillRect(0, 0, W, H);
    var cx = W / 2, cy = H / 2;
    for (var i = 0; i < wstars.length; i++) {
      var s = wstars[i];
      // step along the 3D heading; the perspective divide does the rest
      var step = 0.046 * s.v * ease;
      s.x -= DIR.x * step; s.y -= DIR.y * step; s.z -= DIR.z * step;
      if (s.z <= ZNEAR || s.z >= ZFAR) { wstars[i] = wrecycle(); continue; }

      var sx = cx + (s.x / s.z) * FOCAL;
      var sy = cy + (s.y / s.z) * FOCAL;
      if (s.px !== null) {
        var near = 1 - Math.min(1, s.z / 2);         // brighter the closer it passes
        wctx.strokeStyle = 'rgba(228,224,216,' + (0.05 + near * 0.16).toFixed(3) + ')';
        wctx.lineWidth = Math.max(1, (0.5 + near * 1.4) * DPR);
        wctx.beginPath(); wctx.moveTo(s.px, s.py); wctx.lineTo(sx, sy); wctx.stroke();
      }
      s.px = sx; s.py = sy;
      if (sx < -W * 0.3 || sx > W * 1.3 || sy < -H * 0.3 || sy > H * 1.3) wstars[i] = wrecycle();
    }
    if (wrunning) wraf = requestAnimationFrame(wframe);
  }
  // Starting a jump that is already in flight would re-seed the field and pick a
  // new heading mid-animation — that is what caused the "second jump straight
  // after" glitch. A run in progress is simply left alone.
  // phase: 0 = launching (accelerate), 0.5 = landing (decelerate from the peak).
  // resumed = keep the heading we were handed instead of rolling a new one.
  function warpStart(phase, resumed) {
    if (!wctx) return;
    if (wstopTimer) { clearTimeout(wstopTimer); wstopTimer = 0; }
    if (wrunning) return;
    wsize();
    if (!resumed) wdir();
    wseed();
    wphase0 = phase || 0;
    wt0 = performance.now();
    wrunning = true;
    wframe(wt0);
  }
  function warpStop() {
    if (wstopTimer) { clearTimeout(wstopTimer); wstopTimer = 0; }
    wrunning = false;
    if (wraf) { cancelAnimationFrame(wraf); wraf = 0; }
    if (wctx) wctx.clearRect(0, 0, W, H);          // no stale frame left behind
  }

  function reveal() {
    document.documentElement.classList.add('bhc-ready');
    warp.style.opacity = '0';
    if (wstopTimer) clearTimeout(wstopTimer);
    wstopTimer = setTimeout(warpStop, 620);
  }
  function veilIn(cb) {                             // launch the jump, then run cb (navigate)
    document.documentElement.classList.remove('bhc-ready');
    warp.style.opacity = '1';
    warpStart(0);                                   // accelerating half
    saveJump();                                     // the next page finishes this same jump
    setTimeout(cb, 460);
  }

  // Landing: resume the jump we were handed (same heading, decelerating out of
  // the peak). A fresh arrival with no handoff just decelerates on a new heading.
  warpStart(0.5, takeJump());
  document.addEventListener('DOMContentLoaded', function () {
    if (document.body && warp.parentNode !== document.body) document.body.appendChild(warp);
    if (wrunning) wsize();
  });
  window.addEventListener('resize', function () { if (wrunning) wsize(); });

  function detect() {
    try {
      var u = new URLSearchParams(location.search).get('lang');
      if (SUPPORTED.indexOf(u) !== -1) return u;
    } catch (e) {}
    try {
      var s = localStorage.getItem('bhc_lang');
      if (SUPPORTED.indexOf(s) !== -1) return s;
    } catch (e) {}
    var n = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return SUPPORTED.indexOf(n) !== -1 ? n : 'en';
  }

  var lang = detect();
  window.BHC_LANG = lang;

  // t('key') → string in the active language; tn('nav','overview') → nested
  window.t = function (key) {
    var e = window.STRINGS[key];
    return e ? (e[lang] || e.en || '') : '';
  };
  window.tn = function (group, key) {
    var g = window.STRINGS[group];
    return g && g[lang] ? (g[lang][key] || '') : '';
  };

  window.setLang = function (l) {
    if (SUPPORTED.indexOf(l) === -1 || l === lang) return;
    try { localStorage.setItem('bhc_lang', l); } catch (e) {}
    var target;
    try { var u = new URL(location.href); u.searchParams.set('lang', l); target = u.toString(); }
    catch (e) { target = null; }
    veilIn(function () { if (target) location.href = target; else location.reload(); });
  };

  // fill every [data-i18n], [data-i18n-html], [data-i18n-nav]; wire the selector
  window.BHC_applyI18n = function () {
    document.documentElement.lang = lang;

    // títol, descripció i etiquetes OG segons la pàgina i l'idioma actiu
    (function () {
      var tag = document.querySelector('meta[name="bhc-page"]');
      var pm = tag && (window.PAGEMETA || {})[tag.getAttribute('content')];
      if (!pm) return;
      var m = pm[lang] || pm.ca; if (!m) return;
      document.title = m.t;
      var set = function (sel, val) {
        var el = document.querySelector(sel); if (el) el.setAttribute('content', val);
      };
      set('meta[name="description"]', m.d);
      set('meta[property="og:title"]', m.t);
      set('meta[property="og:description"]', m.d);
      set('meta[name="twitter:title"]', m.t);
      set('meta[name="twitter:description"]', m.d);
      set('meta[property="og:locale"]', lang === 'ca' ? 'ca_ES' : lang === 'es' ? 'es_ES' : 'en_GB');
    })();

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = window.t(el.getAttribute('data-i18n'));
      if (v) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var v = window.t(el.getAttribute('data-i18n-html'));
      if (v) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-nav]').forEach(function (el) {
      var v = window.tn('nav', el.getAttribute('data-i18n-nav'));
      if (v) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var v = window.t(el.getAttribute('data-i18n-ph'));
      if (v) el.setAttribute('placeholder', v);
    });

    // language selector: active in ink, others dim; wire clicks
    document.querySelectorAll('[data-lang-btn]').forEach(function (el) {
      var l = el.getAttribute('data-lang-btn');
      el.style.color = (l === lang) ? 'var(--ink)' : 'var(--t5)';
      if (!el._wired) {
        el._wired = true;
        el.addEventListener('click', function () { window.setLang(l); });
      }
    });
  };

  // The DC framework may mount the page template asynchronously, after DOMContentLoaded.
  // Re-apply a few times so translated text lands regardless of when the template appears.
  function boot() {
    window.BHC_applyI18n();
    [60, 200, 500].forEach(function (ms) { setTimeout(window.BHC_applyI18n, ms); });
    setTimeout(reveal, 300);   // lift the veil once the template has mounted + translated
  }
  if (document.readyState !== 'loading') boot();
  else document.addEventListener('DOMContentLoaded', boot);
  window.addEventListener('load', reveal);   // and no later than full load
  setTimeout(reveal, 1600);                  // hard safety net so it can never stay black

  // Fade to black before following an internal page link.
  document.addEventListener('click', function (e) {
    if (e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    var a = e.target && e.target.closest ? e.target.closest('a') : null;
    if (!a) return;
    var href = a.getAttribute('href') || '';
    if (!/\.dc\.html(\?|#|$)/i.test(href)) return;         // only internal page navigations
    if (a.target && a.target !== '' && a.target !== '_self') return;
    e.preventDefault();
    veilIn(function () { location.href = href; });
  }, true);
})();
